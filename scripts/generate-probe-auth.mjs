import { DatabaseSync } from 'node:sqlite';
import { writeFileSync, mkdirSync } from 'node:fs';
import { getMigrations } from 'better-auth/db/migration';
import { createAuthOptions } from '../probes/deployment/src/auth.ts';

const database = new DatabaseSync(':memory:');
try {
  const options = createAuthOptions({
    DB: database,
    BETTER_AUTH_SECRET: 'schema-generation-only-secret-at-least-32-characters',
    BETTER_AUTH_URL: 'http://probe.local',
  });
  const { compileMigrations } = await getMigrations(options);
  const sql = await compileMigrations();
  mkdirSync('probes/deployment/migrations', { recursive: true });
  writeFileSync('probes/deployment/migrations/0001_auth.sql', `-- Generated by Better Auth 1.7.10 from probes/deployment/src/auth.ts.\n${sql.trim()}\n`);
  console.log('Generated probe auth schema from the installed Better Auth configuration.');
} finally { database.close(); }
